import { readFile, mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
import { build } from "esbuild";
import postcss from "postcss";
import tailwind from "@tailwindcss/postcss";

const root = fileURLToPath(new URL("../", import.meta.url));
const logo = `data:image/png;base64,${(await readFile(resolve(root,'public/mytalent-logo.png'))).toString('base64')}`;
const codexIcon = `data:image/png;base64,${(await readFile(resolve(root,'public/codex-icon.png'))).toString('base64')}`;
const entry = `import React from "react";
import {createRoot} from "react-dom/client";
import Workspace from "./app/components/Workspace";
import HostBridge from "./app/components/HostBridge";
const element = document.getElementById("tutor-root");
createRoot(element).render(<><HostBridge/><Workspace/></>);`;

const javascript = await build({
  absWorkingDir: root,
  stdin: { contents: entry, sourcefile: "mcp-entry.tsx", resolveDir: root, loader: "tsx" },
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: "es2022",
  minify: true,
  define: { "process.env.NODE_ENV": '"production"' },
  plugins:[{name:'inline-logo',setup(builder){builder.onLoad({filter:/Workspace\.tsx$/},async({path})=>({contents:(await readFile(path,'utf8')).replaceAll('"/mytalent-logo.png"',JSON.stringify(logo)).replaceAll('"/codex-icon.png"',JSON.stringify(codexIcon)),loader:'tsx'}));}}],
  tsconfig: resolve(root, "tsconfig.json"),
});
const cssPath = resolve(root, "app/globals.css");
const css = await postcss([tailwind({ base: root })]).process(await readFile(cssPath, "utf8"), { from: cssPath });
const scripts = javascript.outputFiles.filter(file => file.path.endsWith(".js") || file.path === "<stdout>").map(file => file.text).join("\n");
if (!scripts) throw new Error("MCP App JavaScript bundle is empty.");
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>MyTalent Education</title><style>${css.css.replaceAll("</style", "<\\/style")}</style></head><body><div id="tutor-root"></div><script>window.__TUTOR_MCP_APP__=true;</script><script>${scripts.replaceAll("</script", "<\\/script")}</script></body></html>`;
await mkdir(resolve(root, "lib/generated"), { recursive: true });
await writeFile(resolve(root, "lib/generated/mcp-app-html.ts"), `// Generated by scripts/build-mcp-app.mjs. Rebuild after UI changes.\nexport const MCP_APP_HTML = ${JSON.stringify(html)};\n`);
await writeFile(resolve(root, "public/mcp-app.html"), html);
process.stdout.write(`Bundled MCP App HTML: ${Math.round(Buffer.byteLength(html) / 1024)} KiB, with JavaScript and CSS inline.\n`);
